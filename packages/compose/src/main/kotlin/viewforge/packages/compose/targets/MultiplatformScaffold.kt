package viewforge.packages.compose.targets

/**
 * The non-Kotlin text files of an exported **KMP multi-target** project (ADR-036): the Compose
 * Multiplatform `build.gradle.kts` (a `jvm()` desktop target + an `androidTarget()`), the Android
 * manifest, and the Gradle config. The parallel of [GradleScaffold] for the multiplatform export; the
 * generated *UI* Kotlin (screens in `commonMain`, `Main.kt`, `MainActivity.kt`) is built structurally
 * with KotlinPoet elsewhere ([ComposeEntryPoints], [viewforge.packages.compose.codegen.ComposeCodeGenerator]).
 *
 * As with [GradleScaffold], the only user-derived value that enters is the project name — reduced to a
 * `[a-z0-9-]` [GradleScaffold.slug] (and a valid package via [applicationId]) so it cannot alter file
 * structure (ADR-019); the manifest `android:label` is XML-escaped prose. Pinned versions mirror
 * `gradle/libs.versions.toml` (ADR-036) and are duplicated as constants because the catalog is a
 * build-time artifact with no runtime accessor — keep them in lockstep on every bump.
 *
 * NOTE: the generated Android project is **not** compiled by ViewForge's own build (no Android SDK; the
 * in-process Android compile gate is #219, ADR-038). This scaffold is verified structurally by
 * `MultiplatformExporterTest` here; real Android compilation is proven by #219 / the user's toolchain.
 */
internal object MultiplatformScaffold {
    // Mirror gradle/libs.versions.toml (ADR-036). Compose-Android reuses GradleScaffold.COMPOSE_VERSION.
    const val AGP_VERSION = "8.7.3" // libs.versions.toml: agp
    const val ANDROID_MIN_SDK = "24" // libs.versions.toml: androidMinSdk
    const val ANDROID_COMPILE_SDK = "35" // libs.versions.toml: androidCompileSdk
    const val ANDROID_TARGET_SDK = "35" // libs.versions.toml: androidTargetSdk
    const val ACTIVITY_COMPOSE_VERSION = "1.9.3" // libs.versions.toml: activityCompose

    private const val COMPOSE_DEV_REPO = "https://maven.pkg.jetbrains.space/public/p/compose/dev"

    /**
     * A valid Android `namespace`/`applicationId` derived from [slug]: `dev.viewforge.<segment>`, where the
     * segment folds the slug's hyphens to underscores and prefixes `app_` if it would start with a digit
     * (a package segment cannot begin with a digit), so any project name yields a legal package.
     */
    fun applicationId(slug: String): String {
        val segment = slug.replace('-', '_').let { if (it.firstOrNull()?.isDigit() == true) "app_$it" else it }
        return "dev.viewforge.$segment"
    }

    /**
     * `build.gradle.kts` — a runnable Compose Multiplatform module targeting desktop (`jvm`), Android,
     * and web (`wasmJs`). Phase 4 adds the wasmJs browser target (#373): ``CanvasBasedWindow`` renders the
     * generated UI into a ``<canvas>`` element in [indexHtml]. The ``wasmJs`` block configures webpack to
     * output ``app.js`` (the name the generated ``index.html`` references) and marks it as a browser executable.
     * No extra ``wasmJsMain`` dependencies are needed — the ``commonMain`` Compose deps cover the full Wasm
     * target via the Compose Multiplatform plugin.
     *
     * When [smokeTest] is `true` (CI fixture only), a Karma headless-Chrome test task and a `wasmJsTest`
     * dependency block are injected — they are not emitted in regular user exports.
     */
    fun buildGradle(slug: String, smokeTest: Boolean = false): String {
        val appId = applicationId(slug)
        return """
        // Generated by ViewForge project scaffold. Safe to edit — this is now your project.
        // Desktop: ./gradlew run    Android: ./gradlew installDebug    Web: ./gradlew wasmJsBrowserDevelopmentRun
        plugins {
            kotlin("multiplatform") version "${GradleScaffold.KOTLIN_VERSION}"
            id("com.android.application") version "$AGP_VERSION"
            id("org.jetbrains.compose") version "${GradleScaffold.COMPOSE_VERSION}"
            id("org.jetbrains.kotlin.plugin.compose") version "${GradleScaffold.KOTLIN_VERSION}"
        }

        repositories {
            google()
            mavenCentral()
            maven("$COMPOSE_DEV_REPO")
        }

        kotlin {
            jvmToolchain(${GradleScaffold.JVM_TOOLCHAIN})
            jvm()
            androidTarget()
            wasmJs {
                browser {
                    commonWebpackConfig {
                        outputFileName = "app.js"
                    }${karmaTestTask(smokeTest)}
                }
                binaries.executable()
            }

            sourceSets {
                commonMain.dependencies {
                    implementation(compose.runtime)
                    implementation(compose.foundation)
                    implementation(compose.material3)
                    implementation(compose.ui)
                    implementation(compose.components.resources)
                }
                jvmMain.dependencies {
                    implementation(compose.desktop.currentOs)
                }
                androidMain.dependencies {
                    implementation("androidx.activity:activity-compose:$ACTIVITY_COMPOSE_VERSION")
                }${wasmTestDeps(smokeTest)}
            }
        }

        android {
            namespace = "$appId"
            compileSdk = $ANDROID_COMPILE_SDK

            defaultConfig {
                applicationId = "$appId"
                minSdk = $ANDROID_MIN_SDK
                targetSdk = $ANDROID_TARGET_SDK
                versionCode = 1
                versionName = "1.0"
            }

            compileOptions {
                sourceCompatibility = JavaVersion.VERSION_${GradleScaffold.JVM_TOOLCHAIN}
                targetCompatibility = JavaVersion.VERSION_${GradleScaffold.JVM_TOOLCHAIN}
            }
        }

        // Compose Multiplatform resources (#223): generate the `Res` accessor into a fixed package so the
        // generated `commonMain` UI's `Res.drawable.*` imports are deterministic. Drawables live under
        // `src/commonMain/composeResources/drawable/`.
        compose.resources {
            publicResClass = true
            packageOfResClass = "$appId.generated.resources"
        }

        compose.desktop {
            application {
                mainClass = "MainKt"
            }
        }
        """.trimIndent() + "\n"
    }

    /** `settings.gradle.kts` — plugin repositories (incl. `google()` for AGP) plus the project name. */
    fun settingsGradle(slug: String): String =
        """
        // Generated by ViewForge project scaffold.
        pluginManagement {
            repositories {
                google()
                gradlePluginPortal()
                mavenCentral()
                maven("$COMPOSE_DEV_REPO")
            }
        }

        rootProject.name = "$slug"
        """.trimIndent() + "\n"

    fun gradleProperties(): String =
        """
        kotlin.code.style=official
        org.gradle.jvmargs=-Xmx2g -Dfile.encoding=UTF-8
        org.gradle.caching=true
        android.useAndroidX=true
        android.nonTransitiveRClass=true
        """.trimIndent() + "\n"

    fun gitignore(): String =
        """
        .gradle/
        build/
        !gradle/wrapper/gradle-wrapper.jar
        .idea/
        *.iml
        .DS_Store
        local.properties
        .cxx/
        """.trimIndent() + "\n"

    /**
     * `src/androidMain/AndroidManifest.xml`. The launcher activity is bound by the **relative** name
     * `.MainActivity` (leading dot ⇒ AGP resolves it against the module `namespace` from [buildGradle], which
     * equals the `applicationId`), matching the `MainActivity` that [ComposeEntryPoints.androidMainActivity]
     * emits into that same package (#356). A bare name / default-package activity fails to instantiate at
     * runtime because AGP namespaces the manifest name but the class has no package. [name] is the app label,
     * XML-escaped so no metacharacter can alter structure.
     */
    fun androidManifest(name: String): String =
        """
        <?xml version="1.0" encoding="utf-8"?>
        <manifest xmlns:android="http://schemas.android.com/apk/res/android">
            <application
                android:label="${xmlEscape(name.ifBlank { "ViewForge" })}"
                android:theme="@android:style/Theme.Material.Light.NoActionBar">
                <activity
                    android:name=".MainActivity"
                    android:exported="true">
                    <intent-filter>
                        <action android:name="android.intent.action.MAIN" />
                        <category android:name="android.intent.category.LAUNCHER" />
                    </intent-filter>
                </activity>
            </application>
        </manifest>
        """.trimIndent() + "\n"

    /**
     * `src/wasmJsMain/resources/index.html` — the browser shell page for the Kotlin/Wasm target (#373).
     * [CanvasBasedWindow][androidx.compose.ui.window.CanvasBasedWindow] renders the Compose UI into the
     * ``<canvas id="ComposeTarget">`` element; the webpack bundle (``app.js``) bootstraps the Wasm module.
     * [name] is XML-escaped prose only — it never reaches a script or attribute that would execute it.
     */
    fun indexHtml(name: String): String =
        """
        <!DOCTYPE html>
        <html lang="en">
        <head>
            <meta charset="UTF-8">
            <meta name="viewport" content="width=device-width, initial-scale=1.0">
            <title>${xmlEscape(name.ifBlank { "ViewForge" })}</title>
            <style>
                * { margin: 0; padding: 0; box-sizing: border-box; }
                body { background: #fff; }
                canvas { display: block; width: 100vw; height: 100vh; }
            </style>
        </head>
        <body>
            <canvas id="ComposeTarget"></canvas>
            <script src="app.js"></script>
        </body>
        </html>
        """.trimIndent() + "\n"

    /** `README.md` — [name] is prose only (never executed), so it is used verbatim. */
    fun readme(name: String): String =
        """
        # $name

        Generated by [ViewForge](https://viewforge.dev) from `$name.vforge` as a Compose Multiplatform
        project targeting **desktop**, **Android**, and **Web (Kotlin/Wasm)** from shared `commonMain` UI.

        The composables under `src/commonMain/kotlin` are generated output — regenerate them from the
        editor rather than hand-editing, or they will be overwritten on the next export.

        ## Run — desktop

        The desktop target needs only a JDK (17+):

            ./gradlew run

        ## Run — Android

        The Android target needs the **Android SDK**. Point Gradle at it in one of these ways: open this
        folder in **Android Studio** (it writes `local.properties` for you), set the `ANDROID_HOME`
        environment variable to the SDK path, or create a `local.properties` file in the project root with
        the SDK path — use **forward slashes** even on Windows:

            sdk.dir=C:/Users/you/AppData/Local/Android/Sdk

        Then build:

            ./gradlew assembleDebug   # build the APK -> build/outputs/apk/debug/
            ./gradlew installDebug    # build and install to a connected device or emulator

        `local.properties` is machine-specific and is already ignored by `.gitignore`.

        ## Run — Web

        The web target compiles to Kotlin/Wasm and runs in any modern browser. Node.js (20+) must be
        available; Gradle downloads the webpack toolchain automatically on first run.

        Development server with live reload:

            ./gradlew wasmJsBrowserDevelopmentRun

        Production bundle (output in `build/dist/wasmJs/productionExecutable/`):

            ./gradlew wasmJsBrowserProductionWebpack

        To serve the production bundle locally, point any static file server at that directory and open
        `index.html`. The Wasm target is experimental — API stability is not guaranteed between
        Compose Multiplatform versions.
        """.trimIndent() + "\n"

    private fun karmaTestTask(smokeTest: Boolean): String = if (!smokeTest) {
        ""
    } else {
        "\n                    testTask {\n                        useKarma {\n                            useChromeHeadlessNoSandbox()\n                        }\n                    }"
    }

    private fun wasmTestDeps(smokeTest: Boolean): String = if (!smokeTest) {
        ""
    } else {
        "\n                wasmJsTest.dependencies {\n                    implementation(kotlin(\"test\"))\n                }"
    }

    private fun xmlEscape(s: String): String = s
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace("\"", "&quot;")
        .replace("'", "&apos;")
}
