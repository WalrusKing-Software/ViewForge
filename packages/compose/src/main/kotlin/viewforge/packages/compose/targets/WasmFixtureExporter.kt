package viewforge.packages.compose.targets

import viewforge.model.FrameworkRef
import viewforge.model.Node
import viewforge.model.NodeId
import viewforge.model.Project
import viewforge.model.Screen
import viewforge.project.BinaryFile
import viewforge.project.TextFile
import java.io.File

/**
 * Generates a minimal Compose Multiplatform project with `wasmJs` target for the CI smoke test
 * gate (#375). The fixture is a real KMP project with a screen, a wasmJs entry point, and a
 * trivial `SmokeTest` that Karma can run in headless Chrome.
 *
 * The [main] entry point is wired to the `exportWasmFixture` Gradle task in `build.gradle.kts`;
 * the task writes the fixture to `build/wasm-fixture/`. The CI workflow then `cd`s into that
 * directory and runs `wasmJsBrowserTest` against the generated project, which proves the
 * ViewForge-generated Wasm entry point compiles and boots in a real browser engine.
 */
internal object WasmFixtureExporter {
    private val FIXTURE_PROJECT = Project(
        id = "smoke-fixture",
        name = "Smoke",
        framework = FrameworkRef("compose-multiplatform", "1.0.0"),
        screens = listOf(
            Screen(
                "home",
                "Home",
                Node(NodeId("root"), "compose.foundation.layout.Box"),
            ),
        ),
    )

    // Static literal — no user input, no injection risk; KotlinPoet's structural API is for
    // user-derived content. This is fixed CI infrastructure that never varies.
    private val SMOKE_TEST_KT = """
        // Generated by ViewForge CI fixture — do not edit.
        import kotlin.test.Test
        import kotlin.test.assertTrue

        class SmokeTest {
            @Test
            fun smokeWasmLoads() = assertTrue(true)
        }
    """.trimIndent() + "\n"

    @JvmStatic
    fun main(args: Array<String>) {
        val outDir = File(args.getOrElse(0) { error("Usage: WasmFixtureExporter <outputDir>") })
        export(outDir)
    }

    fun export(outDir: File) {
        val slug = GradleScaffold.slug(FIXTURE_PROJECT.name)
        val files = buildList {
            MultiplatformExporter.multiplatformProject(FIXTURE_PROJECT).forEach { file ->
                if (file.path == "build.gradle.kts") {
                    add(TextFile("build.gradle.kts", MultiplatformScaffold.buildGradle(slug, smokeTest = true)))
                } else {
                    add(file)
                }
            }
            add(TextFile("src/wasmJsTest/kotlin/SmokeTest.kt", SMOKE_TEST_KT))
        }
        files.forEach { exportFile ->
            val dest = outDir.resolve(exportFile.path)
            dest.parentFile.mkdirs()
            when (exportFile) {
                is TextFile -> dest.writeText(exportFile.content)
                is BinaryFile -> {
                    dest.writeBytes(exportFile.bytes)
                    if (exportFile.executable) dest.setExecutable(true)
                }
            }
        }
    }
}
