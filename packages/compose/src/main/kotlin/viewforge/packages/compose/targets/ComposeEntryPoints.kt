package viewforge.packages.compose.targets

import com.squareup.kotlinpoet.AnnotationSpec
import com.squareup.kotlinpoet.ClassName
import com.squareup.kotlinpoet.CodeBlock
import com.squareup.kotlinpoet.FileSpec
import com.squareup.kotlinpoet.FunSpec
import com.squareup.kotlinpoet.KModifier
import com.squareup.kotlinpoet.MemberName
import com.squareup.kotlinpoet.TypeSpec
import viewforge.model.Project
import viewforge.packages.compose.codegen.KotlinFormatter
import viewforge.packages.compose.codegen.KotlinIdentifiers
import viewforge.packages.compose.codegen.NavHost

/**
 * The generated **platform entry points** for an exported Compose project — the small per-target files
 * that stand up a window/activity and render the project's first screen. The shared screens themselves
 * come from [viewforge.packages.compose.codegen.ComposeCodeGenerator] and are framework-neutral
 * `commonMain`; only these entry points differ per target (ADR-008/ADR-036).
 *
 * Both are built with KotlinPoet's structural API (CLAUDE.md rule 4) and passed through the G7
 * [KotlinFormatter]. Every generated file — screens, `Theme`, `App`, and these entry points — shares one
 * [packageName], so an entry point references `AppTheme`/`<Screen>`/`App` directly with no import. The
 * desktop-only export leaves it `""` (the default package, byte-identical to before); the KMP/Android
 * export sets it to the app's `applicationId`, because an Android launcher activity **must** live in a
 * real (namespaced) package — a default-package `MainActivity` can't be named in the manifest under a
 * `namespace`, which AGP always qualifies, so it fails to instantiate at runtime (#356).
 */
internal object ComposeEntryPoints {
    /** The desktop entry-point file name (`jvmMain`), also the class Gradle runs (`mainClass = "MainKt"`). */
    const val MAIN_KT = "Main.kt"

    /** The Android entry-point file name (`androidMain`); the manifest points its launcher activity here. */
    const val MAIN_ACTIVITY_KT = "MainActivity.kt"

    /** The wasmJs browser entry-point file name (`wasmJsMain`); same filename as the desktop entry, different source set. */
    const val MAIN_WASM_KT = MAIN_KT

    private val application = MemberName("androidx.compose.ui.window", "application")
    private val windowFn = MemberName("androidx.compose.ui.window", "Window")
    private val setContent = MemberName("androidx.activity.compose", "setContent")
    private val materialTheme = MemberName("androidx.compose.material3", "MaterialTheme")

    // Android edge-to-edge inset handling (#358). On targetSdk 35 edge-to-edge is enforced, so an activity
    // that does nothing gets a translucent system compatibility scrim over the bars and lays interactive
    // content out *under* them. These stand up opaque, theme-coloured bars with inset-padded content.
    private val enableEdgeToEdge = MemberName("androidx.activity", "enableEdgeToEdge")
    private val surface = MemberName("androidx.compose.material3", "Surface")
    private val box = MemberName("androidx.compose.foundation.layout", "Box")
    private val fillMaxSize = MemberName("androidx.compose.foundation.layout", "fillMaxSize")
    private val safeDrawingPadding = MemberName("androidx.compose.foundation.layout", "safeDrawingPadding")
    private val modifier = ClassName("androidx.compose.ui", "Modifier")

    /** The generated project theme wrapper (`Theme.kt`), in the same [packageName] as the screens. */
    private fun appTheme(packageName: String) = MemberName(packageName, "AppTheme")

    private val componentActivity = ClassName("androidx.activity", "ComponentActivity")
    private val bundle = ClassName("android.os", "Bundle")

    /**
     * The desktop `main()` (`jvmMain`): opens an [application] [windowFn], wraps the first screen in the
     * project's [appTheme] wrapper when [themed] (else a default [materialTheme]), and renders it. With no
     * screens it opens an empty themed window rather than failing.
     */
    fun desktopMain(project: Project, themed: Boolean, packageName: String = ""): String {
        val entry = entryComposable(project, packageName)
        val title = project.name.ifBlank { "ViewForge" }
        val theme = if (themed) appTheme(packageName) else materialTheme
        val body = CodeBlock.builder()
            .beginControlFlow("%M", application)
            .beginControlFlow("%M(onCloseRequest = ::exitApplication, title = %S)", windowFn, title)
            .apply {
                if (entry != null) {
                    beginControlFlow("%M", theme)
                    addStatement("%M()", entry)
                    endControlFlow()
                } else {
                    addStatement("%M { }", theme)
                }
            }
            .endControlFlow()
            .endControlFlow()
            .build()

        val file = FileSpec.builder(packageName, "Main")
            .addFileComment("Generated by ViewForge — do not edit.\n%L", sourceLine(project))
            .indent("    ")
            .addFunction(FunSpec.builder("main").addCode(body).build())
            .build()
            .toString()
        return KotlinFormatter.format(file)
    }

    /**
     * The Android `MainActivity` (`androidMain`): a `ComponentActivity` whose `onCreate` calls
     * [setContent], wrapping the first screen in the `AppTheme` wrapper when [themed] (else a default
     * [materialTheme]). Emitted in [packageName] (the app's `applicationId`) so it both sees the
     * `commonMain` `AppTheme`/`<Screen>` (same package) and can be named by the manifest as
     * `.MainActivity` under that `namespace` — the pairing that makes it instantiate at runtime (#356).
     *
     * It also handles edge-to-edge insets (#358): `enableEdgeToEdge()` clears the API-35 compatibility
     * scrim, a full-window [surface] paints the system-bar regions solid (opaque, theme-coloured bars),
     * and the content is wrapped in [safeDrawingPadding] so it — and its touch targets — never sit under
     * the bars. Without this the exported app shows grey scrims over the bars and taps on content laid out
     * beneath them are swallowed by the system bar.
     */
    fun androidMainActivity(project: Project, themed: Boolean, packageName: String = ""): String {
        val entry = entryComposable(project, packageName)
        val theme = if (themed) appTheme(packageName) else materialTheme
        val onCreate = FunSpec.builder("onCreate")
            .addModifiers(KModifier.OVERRIDE)
            .addParameter("savedInstanceState", bundle.copy(nullable = true))
            .addStatement("super.onCreate(savedInstanceState)")
            .addStatement("%M()", enableEdgeToEdge)
            .beginControlFlow("%M", setContent)
            .beginControlFlow("%M", theme)
            .beginControlFlow("%M(modifier = %T.%M())", surface, modifier, fillMaxSize)
            .apply {
                if (entry != null) {
                    beginControlFlow("%M(modifier = %T.%M())", box, modifier, safeDrawingPadding)
                    addStatement("%M()", entry)
                    endControlFlow()
                }
            }
            .endControlFlow() // Surface
            .endControlFlow() // theme
            .endControlFlow() // setContent
            .build()

        val activity = TypeSpec.classBuilder("MainActivity")
            .superclass(componentActivity)
            .addFunction(onCreate)
            .build()

        val file = FileSpec.builder(packageName, "MainActivity")
            .addFileComment("Generated by ViewForge — do not edit.\n%L", sourceLine(project))
            .indent("    ")
            .addType(activity)
            .build()
            .toString()
        return KotlinFormatter.format(file)
    }

    /**
     * The Kotlin/Wasm browser ``main()`` (`wasmJsMain`): renders the project's entry composable inside
     * [CanvasBasedWindow], which mounts onto the ``<canvas id="ComposeTarget">`` element in the generated
     * [MultiplatformScaffold.indexHtml]. The [appTheme] wrapper is applied when [themed], else a default
     * [materialTheme]. With no screens an empty themed window is opened rather than failing.
     *
     * [CanvasBasedWindow] is ``@ExperimentalComposeUiApi``; a file-level ``@OptIn`` is emitted so the
     * generated entry compiles without the caller opting in separately.
     */
    fun wasmJsMain(project: Project, themed: Boolean, packageName: String = ""): String {
        val entry = entryComposable(project, packageName)
        val title = project.name.ifBlank { "ViewForge" }
        val theme = if (themed) appTheme(packageName) else materialTheme
        val canvasBasedWindow = MemberName("androidx.compose.ui.window", "CanvasBasedWindow")
        val experimentalComposeUiApi = ClassName("androidx.compose.ui", "ExperimentalComposeUiApi")

        val body = CodeBlock.builder()
            .beginControlFlow("%M(%S)", canvasBasedWindow, title)
            .apply {
                if (entry != null) {
                    beginControlFlow("%M", theme)
                    addStatement("%M()", entry)
                    endControlFlow()
                } else {
                    addStatement("%M { }", theme)
                }
            }
            .endControlFlow()
            .build()

        val optIn = AnnotationSpec.builder(ClassName("kotlin", "OptIn"))
            .addMember("%T::class", experimentalComposeUiApi)
            .useSiteTarget(AnnotationSpec.UseSiteTarget.FILE)
            .build()

        val file = FileSpec.builder(packageName, "Main")
            .addFileComment("Generated by ViewForge — do not edit.\n%L", sourceLine(project))
            .addAnnotation(optIn)
            .indent("    ")
            .addFunction(FunSpec.builder("main").addCode(body).build())
            .build()
            .toString()
        return KotlinFormatter.format(file)
    }

    /**
     * The composable an entry point renders: the generated [NavHost.APP_FN] host when the project has any
     * screen-to-screen navigation (ADR-039, #214) — so the entry stands up the screen switcher — else the first
     * screen directly (byte-identical to before navigation existed), or null when the project has no screens.
     */
    private fun entryComposable(project: Project, packageName: String): MemberName? = when {
        NavHost.projectNavigates(project) -> MemberName(packageName, NavHost.APP_FN)
        else ->
            project.screens.firstOrNull()
                ?.let { MemberName(packageName, KotlinIdentifiers.requireFunctionName(it.name)) }
    }

    private fun sourceLine(project: Project): String =
        "Source: ${project.name.ifBlank { "Project" }}.vforge (schema ${project.schemaVersion})"
}
